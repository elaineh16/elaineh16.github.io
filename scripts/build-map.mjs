// Rasterises Natural Earth country shapes (via world-atlas) into small pixel grids
// for the Minecraft-style travel map. Output: data/map-grid.ts in the site repo.
import fs from "node:fs"
import { feature } from "topojson-client"

const topo = JSON.parse(fs.readFileSync(new URL("../node_modules/world-atlas/countries-50m.json", import.meta.url)))
const countries = feature(topo, topo.objects.countries).features

// Country codes (ISO numeric ids in world-atlas)
const CODE = { "840": "U", "124": "C", "484": "M" } // USA, Canada, Mexico; others -> "L"

const LAKES = [
  [[-92.1,46.7],[-90.4,46.6],[-88.4,47.4],[-86.5,46.6],[-84.6,46.5],[-84.8,47.8],[-86.0,48.7],[-88.3,48.8],[-89.6,48.0]],
  [[-87.8,41.7],[-86.8,41.8],[-86.2,43.0],[-86.4,44.6],[-85.5,45.6],[-84.8,45.8],[-85.6,46.0],[-87.0,45.8],[-87.6,44.8],[-87.9,43.5]],
  [[-84.6,45.9],[-83.5,46.1],[-81.6,46.0],[-80.4,45.4],[-79.8,44.6],[-81.7,44.2],[-82.4,43.0],[-82.9,43.9],[-83.5,44.2],[-84.0,45.0]],
  [[-83.4,41.7],[-82.0,41.4],[-80.5,41.9],[-79.0,42.8],[-80.3,42.6],[-81.5,42.3],[-83.1,42.0]],
  [[-79.8,43.25],[-78.0,43.35],[-76.3,43.5],[-76.2,44.15],[-77.5,44.0],[-79.1,43.75],[-79.55,43.55]],
]

function inRing(x, y, ring) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j]
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}
function inPolygon(x, y, poly) {
  if (!inRing(x, y, poly[0])) return false
  for (let k = 1; k < poly.length; k++) if (inRing(x, y, poly[k])) return false
  return true
}
function bbox(f) {
  let a = [180, 90, -180, -90]
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates
  for (const p of polys) for (const [x, y] of p[0]) { a = [Math.min(a[0], x), Math.min(a[1], y), Math.max(a[2], x), Math.max(a[3], y)] }
  return a
}
const shapes = countries.filter((f) => f.geometry).map((f) => ({ code: CODE[f.id] || "L", box: bbox(f), polys: f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates }))

function grid({ lonMin, lonMax, latMin, latMax, width }) {
  const k = Math.cos((((latMin + latMax) / 2) * Math.PI) / 180)
  const height = Math.round((width * (latMax - latMin)) / ((lonMax - lonMin) * k))
  const rows = []
  for (let r = 0; r < height; r++) {
    let row = ""
    const lat = latMax - ((r + 0.5) / height) * (latMax - latMin)
    for (let c = 0; c < width; c++) {
      const lon = lonMin + ((c + 0.5) / width) * (lonMax - lonMin)
      let ch = "."
      if (LAKES.some((ring) => inRing(lon, lat, ring))) ch = "~"
      else
        for (const s of shapes) {
          if (lon < s.box[0] || lon > s.box[2] || lat < s.box[1] || lat > s.box[3]) continue
          if (s.polys.some((p) => inPolygon(lon, lat, p))) { ch = s.code; break }
        }
      row += ch
    }
    rows.push(row)
  }
  return { lonMin, lonMax, latMin, latMax, width, height, rows }
}

const views = {
  na: grid({ lonMin: -128, lonMax: -58, latMin: 18, latMax: 58, width: 128 }),
  east: grid({ lonMin: -92, lonMax: -63, latMin: 33.5, latMax: 48.5, width: 128 }),
}
const out = `// Generated by scripts/build-map.mjs from Natural Earth data (public domain) via world-atlas.
// Characters: "." water, "~" lake, "U" USA, "C" Canada, "M" Mexico, "L" other land.
export interface MapGrid { lonMin: number; lonMax: number; latMin: number; latMax: number; width: number; height: number; rows: string[] }
export const MAP_VIEWS: Record<"na" | "east", MapGrid> = ${JSON.stringify(views)}
`
fs.writeFileSync(process.argv[2], out)
